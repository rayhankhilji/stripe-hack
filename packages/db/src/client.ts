import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { PGlite } from "@electric-sql/pglite";
import { getTableName, isTable, sql, type SQL, type Table } from "drizzle-orm";
import { drizzle as drizzlePglite, type PgliteDatabase } from "drizzle-orm/pglite";
import { migrate as migratePglite } from "drizzle-orm/pglite/migrator";
import { drizzle as drizzlePostgres, type PostgresJsDatabase } from "drizzle-orm/postgres-js";
import { migrate as migratePostgres } from "drizzle-orm/postgres-js/migrator";
import postgres from "postgres";
import * as schema from "./schema";
import { migrationsFolder, pgliteDataDir } from "./paths";

export type Db = PgliteDatabase<typeof schema> | PostgresJsDatabase<typeof schema>;

type Handle =
  | { kind: "pglite"; db: PgliteDatabase<typeof schema>; client: PGlite }
  | { kind: "postgres"; db: PostgresJsDatabase<typeof schema>; client: postgres.Sql };

type DbGlobal = { handle?: Handle; migrated?: Promise<void> };

// Kept on globalThis so Next.js dev reloads reuse one connection (PGlite allows a single opener per directory).
const store = globalThis as typeof globalThis & { __ghostDb?: DbGlobal };
const state: DbGlobal = (store.__ghostDb ??= {});

function openPglite(dataDir: string): Handle {
  if (!dataDir.includes("://")) {
    mkdirSync(dataDir, { recursive: true });
    // The data dir lives under <repo>/.data; keep it out of git without touching the root .gitignore.
    const ignore = join(dirname(dataDir), ".gitignore");
    if (!existsSync(ignore)) writeFileSync(ignore, "*\n");
  }
  const client = new PGlite(dataDir);
  return { kind: "pglite", client, db: drizzlePglite({ client, schema }) };
}

function openPostgres(url: string): Handle {
  // prepare:false keeps us compatible with Supabase's transaction pooler (pgbouncer).
  const client = postgres(url, { max: 5, prepare: false, onnotice: () => undefined });
  return { kind: "postgres", client, db: drizzlePostgres({ client, schema }) };
}

function handle(): Handle {
  if (!state.handle) {
    const url = process.env.DATABASE_URL;
    state.handle = url ? openPostgres(url) : openPglite(pgliteDataDir());
  }
  return state.handle;
}

/** Singleton drizzle database. DATABASE_URL set → postgres-js; otherwise PGlite at <repo>/.data/pglite. */
export function getDb(): Db {
  return handle().db;
}

/** Applies packages/db/drizzle/*.sql (generated by drizzle-kit from schema.ts). Safe to call repeatedly. */
export async function migrate(): Promise<void> {
  if (!state.migrated) {
    const h = handle();
    const opts = { migrationsFolder: migrationsFolder() };
    state.migrated = (h.kind === "pglite" ? migratePglite(h.db, opts) : migratePostgres(h.db, opts)).catch(
      (err: unknown) => {
        state.migrated = undefined;
        throw err;
      },
    );
  }
  return state.migrated;
}

/** Every table in the schema, by its SQL name. */
export function tableNames(): string[] {
  const values: unknown[] = Object.values(schema);
  return values.filter((t): t is Table => isTable(t)).map((t) => getTableName(t));
}

/** Truncates every Ghost table (demo reset). The schema and migration history are kept. */
export async function resetDatabase(): Promise<void> {
  await migrate();
  const list = tableNames()
    .map((n) => `"${n}"`)
    .join(", ");
  await getDb().execute(sql.raw(`TRUNCATE TABLE ${list} RESTART IDENTITY CASCADE`));
}

/** Closes the connection and forgets the singleton (tests, CLI shutdown). */
export async function closeDb(): Promise<void> {
  const h = state.handle;
  state.handle = undefined;
  state.migrated = undefined;
  if (!h) return;
  if (h.kind === "pglite") await h.client.close();
  else await h.client.end({ timeout: 5 });
}

/** Runs raw SQL and returns its rows on either driver (postgres-js returns an array, PGlite `{ rows }`). */
export async function queryRows<T extends Record<string, unknown>>(query: SQL): Promise<T[]> {
  const res: unknown = await getDb().execute(query);
  if (Array.isArray(res)) return res as T[];
  return (res as { rows: T[] }).rows;
}
